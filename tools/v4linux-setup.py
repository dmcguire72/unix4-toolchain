class Plan:
    def __init__(self):
        self.bin_dir = ""
        self.kind = "local"
        self.local_root = ""
        self.url = ""
        self.variant = ""
        self.cache_dir = ""
        self.download = False
        self.replace_active = False

    @property
    def label(self) -> str:
        return {"cache": f"Unix v4 ({self.variant})", "url": "Unix v4 (custom URL)"}.get(
            self.kind, "Unix v4 (local directory)")

def make_plan(args, ui, interactive: bool, destdir: str):
    plan = Plan()
    plan.bin_dir = args.bin_dir

    if args.root:
        if is_url(args.root):
            plan.kind, plan.url, plan.download = "url", args.root, True
        else:
            plan.kind, plan.local_root = "local", os.path.abspath(args.root)
    else:
        variant = args.variant
        if not variant:
            if interactive:
                choice = ui.menu(
                    "Emulator -- Filesystem",
                    "The emulator needs a Unix Fourth Edition system image. It will be downloaded now.",
                    [("Stock", "The original, unmodified Fourth Edition image."),
                     ("With symbols", "Same system rebuilt with symbols: readable stack traces and "
                                      "accurate time hooks."),
                     ("Cancel", "")])
                if choice is None or choice == 2:
                    return None
                variant = ("stock", "symbols")[choice]
            elif args.yes:
                variant = "stock"
            else:
                raise InstallError(
                    "no Unix v4 root specified. Pass a directory or URL as the second argument, "
                    "or use --variant stock|symbols (or --yes for stock).")
        plan.kind, plan.variant = "cache", variant
        plan.url = STOCK_URL if variant == "stock" else SYMBOLS_URL
        plan.cache_dir = os.path.join(os.path.abspath(args.cache_dir), variant)
        plan.download = True
        if os.path.isdir(plan.cache_dir) and os.listdir(plan.cache_dir):
            if args.redownload:
                pass
            elif args.no_redownload or args.yes or not interactive:
                plan.download = False
            else:
                short = os.path.relpath(plan.cache_dir)
                if short.startswith(".."):
                    short = plan.cache_dir
                choice = ui.menu(f"emulator -- '{short}' already exists",
                                 "A copy of this Unix v4 image was downloaded earlier.",
                                 [("Use the existing copy", ""), ("Download it again", ""), ("Cancel", "")])
                if choice is None or choice == 2:
                    return None
                plan.download = choice == 1
            if not plan.download:
                plan.local_root = plan.cache_dir

    if not destdir and not args.dry_run and (is_mountpoint(GUEST_ROOT) or is_mountpoint(HOST_STAGING)):
        if args.yes:
            plan.replace_active = True
        elif interactive:
            choice = ui.menu("v4linux is already installed",
                             f"{GUEST_ROOT} is mounted. Replacing it stops the service and unmounts "
                             "the guest environment first. Guest changes stored in the overlay are kept.",
                             [("Replace the running installation", ""), ("Cancel", "")])
            if choice != 0:
                return None
            plan.replace_active = True
        else:
            raise InstallError(f"{GUEST_ROOT} is already mounted. Re-run with --yes to replace it, "
                               "or run 'sudo v4-uninstall' first.")
    return plan


def build_steps(plan: Plan, destdir: str):
    steps = [("preflight", "Check system and inputs", 1)]
    if plan.replace_active:
        steps.append(("stop_old", "Stop running guest environment", 1))
    if plan.download:
        steps.append(("download", f"Download {plan.label}", 8))
        steps.append(("extract", "Extract archive", 5))
    steps += [
        ("root", "Install Unix v4 root", 4),
        ("bin", "Install emulator and toolchain", 2),
        ("man", "Install manual pages", 1),
        ("magic", "Register v4dump file type", 1),
        ("service", "Write service files", 1),
        ("activate", "Mount guest and register binfmt", 3),
        ("verify", "Verify installation", 1),
    ]
    return steps

class Installer:
    def __init__(self, args, plan: Plan, model: tui.Model):
        self.a = args
        self.plan = plan
        self.m = model
        self.destdir = os.path.realpath(args.destdir) if args.destdir else ""
        self.dry = args.dry_run
        self.is_root = os.geteuid() == 0
        self.temp: list[str] = []
        self.undo: list = []
        self.v4_source = ""
        self.archive = ""
        self.systemd = False
        self.activating = not (self.destdir or self.dry)
        self.info: dict[str, str] = {}

    def D(self, path: str) -> str:
        return self.destdir + path if self.destdir else path

    def log(self, text: str):
        self.m.add_log(text)

    def tick(self):
        if self.m.cancelled:
            raise Cancelled()

    def sh(self, *cmd: str, check: bool = True, timeout: float | None = None):
        self.log("$ " + " ".join(shlex.quote(c) for c in cmd))
        if self.dry:
            return 0, ""
        try:
            proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                  text=True, timeout=timeout)
        except FileNotFoundError:
            raise InstallError(f"required command not found: {cmd[0]}")
        except subprocess.TimeoutExpired:
            raise InstallError(f"'{cmd[0]}' timed out after {timeout:.0f}s")
        except OSError as exc:
            raise InstallError(f"cannot run {cmd[0]}: {exc.strerror or exc}")
        out = proc.stdout.strip()
        for line in out.splitlines():
            self.log("  " + line)
        if check and proc.returncode:
            last = out.splitlines()[-1] if out else "no output"
            raise InstallError(f"'{' '.join(cmd[:2])}' failed (exit {proc.returncode}): {last}")
        return proc.returncode, out

    def run_step(self, key: str, fn):
        self.tick()
        self.m.begin(key)
        try:
            outcome = fn()
        except (Cancelled, KeyboardInterrupt):
            self.m.end(tui.WARN, "cancelled")
            raise
        except BaseException:
            self.m.end(tui.FAILED)
            raise
        status, note = tui.DONE, ""
        if isinstance(outcome, tuple):
            status, note = outcome
        elif isinstance(outcome, str):
            note = outcome
        self.m.end(status, note)

    def skip(self, key: str, note: str):
        self.m.skip(key, note)

    def need_root(self):
        if self.activating and not self.is_root:
            raise InstallError("this installer must run as root. Try: sudo make install")

    def execute(self):
        try:
            seq = [("preflight", self.s_preflight)]
            if self.plan.replace_active:
                seq.append(("stop_old", self.s_stop_old))
            if self.plan.download:
                seq += [("download", self.s_download), ("extract", self.s_extract)]
            seq += [("root", self.s_root), ("bin", self.s_bin), ("man", self.s_man),
                    ("magic", self.s_magic), ("service", self.s_service)]
            for key, fn in seq:
                self.run_step(key, fn)
            if self.activating:
                self.run_step("activate", self.s_activate)
            else:
                self.skip("activate", "dry run" if self.dry else "staged install (--destdir)")
            if self.activating:
                self.run_step("verify", self.s_verify)
            else:
                self.skip("verify", "dry run" if self.dry else "staged install (--destdir)")
            self.undo.clear()
            self.build_summary()
            self.m.finish("ok")
        except (Cancelled, KeyboardInterrupt):
            self.rollback()
            self.m.finish("cancelled")
        except InstallError as exc:
            self.rollback()
            self.m.finish("failed", str(exc))
        except Exception as exc:
            self.log(traceback.format_exc())
            self.rollback()
            self.m.finish("failed", f"unexpected error: {exc!r} (see {LOG_FILE} for the traceback)")
        finally:
            self.cleanup()

    def rollback(self):
        while self.undo:
            label, fn = self.undo.pop()
            self.log(f"rolling back: {label}")
            try:
                fn()
            except Exception as exc:
                self.log(f"  rollback step failed: {exc!r}")

    def cleanup(self):
        for path in self.temp:
            try:
                if os.path.isdir(path) and not os.path.islink(path):
                    shutil.rmtree(path, ignore_errors=True)
                elif os.path.lexists(path):
                    os.unlink(path)
            except OSError:
                pass
        self.temp.clear()

    def s_preflight(self):
        self.need_root()
        bin_src = os.path.realpath(self.plan.bin_dir)
        if not os.path.isdir(bin_src):
            raise InstallError(f"bin directory not found: {self.plan.bin_dir} (run 'make' first)")
        for exe in ("v4linux", "v4linux-dispatch"):
            p = os.path.join(bin_src, exe)
            if not (os.path.isfile(p) and os.access(p, os.X_OK)):
                raise InstallError(f"expected executable {p} (run 'make' first)")
        missing = [t for t in REQUIRED_TOOLS if not os.path.isfile(os.path.join(bin_src, t))]
        if missing:
            raise InstallError(f"missing from {bin_src}: {', '.join(missing)} (run 'make' first)")
        self.bin_src = bin_src

        self.magic_src = os.path.join(HERE, "dumpinfo", "v4dump.magic")
        if not (os.path.isfile(self.magic_src) and not os.path.islink(self.magic_src)):
            raise InstallError(f"expected regular magic definition file: {self.magic_src}")
        self.uninstall_script = os.path.join(HERE, "v4linux-uninstall.sh")
        self.uninstall_boot = os.path.join(HERE, "v4linux-uninstall-boot.sh")
        for p in (self.uninstall_script, self.uninstall_boot):
            if not os.path.isfile(p):
                raise InstallError(f"cannot find {p}")

        self.man_src = os.path.join(os.path.dirname(bin_src), "man")
        self.man_pages = self.collect_man_pages()

        if self.plan.local_root:
            self.v4_source = self.check_v4_root(self.plan.local_root)
            self.log(f"Unix v4 root: {self.v4_source}")

        if self.activating:
            if shutil.which("mount") is None or shutil.which("umount") is None:
                raise InstallError("'mount' and 'umount' (util-linux) are required")
            if not self.plan.replace_active and (is_mountpoint(GUEST_ROOT) or is_mountpoint(HOST_STAGING)):
                raise InstallError(f"{GUEST_ROOT} is already mounted; run 'sudo v4-uninstall' first.")
            if not self.fs_supported("overlay"):
                self.sh("modprobe", "overlay", check=False)
                if not self.fs_supported("overlay"):
                    raise InstallError("the kernel has no OverlayFS support (modprobe overlay failed)")
            if not os.path.isdir(BINFMT_DIR) and not is_mountpoint(BINFMT_DIR):
                self.sh("modprobe", "binfmt_misc", check=False)
                if not self.fs_supported("binfmt_misc"):
                    raise InstallError("the kernel has no binfmt_misc support")
            self.systemd = os.path.isdir("/run/systemd/system") and shutil.which("systemctl") is not None
            if not self.systemd:
                self.m.warn("systemd not detected: the guest mounts will not survive a reboot")

    @staticmethod
    def fs_supported(name: str) -> bool:
        try:
            with open("/proc/filesystems") as fh:
                return any(line.split()[-1] == name for line in fh if line.strip())
        except OSError:
            return False

    def check_v4_root(self, path: str) -> str:
        if not os.path.isdir(path):
            raise InstallError(f"Unix v4 root is not a directory: {path}")
        root = resolve_root_dir(path)
        if not os.path.isdir(os.path.join(root, "bin")):
            raise InstallError(f"{path} does not look like a Unix v4 root (no bin/ directory)")
        return root

    def s_stop_old(self):
        if self.dry:
            return "dry run"
        self.deactivate()
        if is_mountpoint(GUEST_ROOT):
            raise InstallError(f"could not unmount {GUEST_ROOT}; close any shells or programs "
                               "using it and try again.")
        return "stopped"

    def s_download(self):
        if self.dry:
            self.log(f"would download {self.plan.url}")
            return "dry run"
        fd, path = tempfile.mkstemp(prefix="v4_dl.", suffix=".tar.xz")
        os.close(fd)
        self.temp.append(path)
        self.archive = path
        last_err = None
        for attempt in range(1, 4):
            try:
                size = self._fetch(self.plan.url, path)
                return tui.human_bytes(size)
            except (urllib.error.URLError, OSError, TimeoutError) as exc:
                last_err = exc
                self.log(f"download attempt {attempt} failed: {exc}")
                if attempt < 3:
                    self.m.update(None, f"retrying in {2 ** attempt}s ({exc})")
                    for _ in range(2 ** attempt * 10):
                        self.tick()
                        time.sleep(0.1)
        raise InstallError(f"download failed after 3 attempts: {last_err}")

    def _fetch(self, url: str, path: str) -> int:
        req = urllib.request.Request(url, headers={"User-Agent": "v4linux-setup"})
        with urllib.request.urlopen(req, timeout=30) as resp, open(path, "wb") as out:
            total = int(resp.headers.get("Content-Length") or 0)
            done, t0, last_t, last_done, rate = 0, time.monotonic(), time.monotonic(), 0, 0.0
            while True:
                self.tick()
                chunk = resp.read(65536)
                if not chunk:
                    break
                out.write(chunk)
                done += len(chunk)
                now = time.monotonic()
                if now - last_t >= 0.25:
                    inst = (done - last_done) / (now - last_t)
                    rate = inst if rate == 0 else 0.7 * rate + 0.3 * inst
                    last_t, last_done = now, done
                    detail = f"{tui.human_bytes(done)}"
                    if total:
                        detail += f" / {tui.human_bytes(total)}"
                    if rate:
                        detail += f"  {tui.human_bytes(rate)}/s"
                        if total and rate > 0:
                            detail += f"  ETA {tui.human_time((total - done) / rate)}"
                    self.m.update(done / total if total else None, detail)
        if total and done != total:
            raise OSError(f"incomplete download ({done} of {total} bytes)")
        if done == 0:
            raise OSError("server returned an empty file")
        self.log(f"downloaded {done} bytes in {time.monotonic() - t0:.1f}s")
        return done

    def s_extract(self):
        if self.dry:
            return "dry run"
        if self.plan.kind == "cache":
            target = self.plan.cache_dir + ".partial"
            os.makedirs(os.path.dirname(target), exist_ok=True)
        else:
            target = tempfile.mkdtemp(prefix="v4_extracted.")
        if os.path.lexists(target):
            shutil.rmtree(target)
        os.makedirs(target)
        self.temp.append(target)

        size = max(1, os.path.getsize(self.archive))
        count = 0
        with open(self.archive, "rb") as raw:
            try:
                tar = tarfile.open(fileobj=raw, mode="r|*")
            except (tarfile.TarError, OSError) as exc:
                raise InstallError(f"cannot read the downloaded archive: {exc}")
            with tar:
                def members():
                    nonlocal count
                    for member in tar:
                        self.tick()
                        self.check_member(member, target)
                        count += 1
                        self.m.update(min(1.0, raw.tell() / size), f"{count} entries  {member.name[:40]}")
                        yield member
                kwargs = {"filter": (lambda member, _path: member)} if hasattr(tarfile, "data_filter") else {}
                try:
                    tar.extractall(target, members=members(), **kwargs)
                except (tarfile.TarError, OSError, EOFError) as exc:
                    raise InstallError(f"extraction failed: {exc}")
        os.unlink(self.archive)
        self.temp.remove(self.archive)

        final = target
        if self.plan.kind == "cache":
            if os.path.lexists(self.plan.cache_dir):
                shutil.rmtree(self.plan.cache_dir)
            os.rename(target, self.plan.cache_dir)
            self.temp.remove(target)
            final = self.plan.cache_dir
        self.v4_source = self.check_v4_root(final)
        self.log(f"Unix v4 root: {self.v4_source}")
        return f"{count} entries"

    @staticmethod
    def check_member(member: tarfile.TarInfo, target: str):
        name = member.name
        parts = [p for p in name.split("/") if p]
        if name.startswith("/") or ".." in parts:
            raise InstallError(f"unsafe path in archive: {name}")
        if member.issym() or member.islnk():
            link = member.linkname
            base = os.path.dirname(name) if member.issym() else ""
            resolved = os.path.normpath(os.path.join(base, link))
            if link.startswith("/") or resolved.startswith(".."):
                raise InstallError(f"unsafe link in archive: {name} -> {link}")

    def chown_like(self, path: str, st: os.stat_result, follow: bool = True):
        if self.is_root:
            try:
                (os.chown if follow else os.lchown)(path, st.st_uid, st.st_gid)
            except OSError as exc:
                self.log(f"  chown {path}: {exc}")

    def copy_tree(self, src: str, dst: str, progress: bool = True) -> int:
        items: list[tuple[str, os.stat_result]] = []
        stack = [src]
        while stack:
            d = stack.pop()
            with os.scandir(d) as it:
                entries = sorted(it, key=lambda e: e.name)
            for e in entries:
                st = e.stat(follow_symlinks=False)
                items.append((e.path, st))
                if stat.S_ISDIR(st.st_mode):
                    stack.append(e.path)
        items.sort(key=lambda x: x[0])
        os.makedirs(dst, exist_ok=True)
        total, dirs = len(items), []
        last = 0.0
        for i, (path, st) in enumerate(items, 1):
            self.tick()
            rel = os.path.relpath(path, src)
            out = os.path.join(dst, rel)
            mode = st.st_mode
            if stat.S_ISDIR(mode):
                if os.path.islink(out) or (os.path.lexists(out) and not os.path.isdir(out)):
                    os.unlink(out)
                os.makedirs(out, exist_ok=True)
                dirs.append((out, st))
            else:
                if os.path.lexists(out):
                    if os.path.isdir(out) and not os.path.islink(out):
                        raise InstallError(f"cannot replace directory with file: {out}")
                    os.unlink(out)
                if stat.S_ISLNK(mode):
                    os.symlink(os.readlink(path), out)
                    self.chown_like(out, st, follow=False)
                elif stat.S_ISREG(mode):
                    shutil.copyfile(path, out)
                    self.chown_like(out, st)
                    os.chmod(out, stat.S_IMODE(mode))
                    os.utime(out, ns=(st.st_atime_ns, st.st_mtime_ns))
                elif stat.S_ISCHR(mode) or stat.S_ISBLK(mode):
                    try:
                        os.mknod(out, mode, st.st_rdev)
                        self.chown_like(out, st)
                    except PermissionError:
                        self.log(f"  skipped device node (need root): {rel}")
                elif stat.S_ISFIFO(mode):
                    os.mkfifo(out, stat.S_IMODE(mode))
                else:
                    self.log(f"  skipped special file: {rel}")
            now = time.monotonic()
            if progress and (now - last > 0.05 or i == total):
                last = now
                self.m.update(i / total, f"{i}/{total} files")
        for out, st in reversed(dirs):
            self.chown_like(out, st)
            os.chmod(out, stat.S_IMODE(st.st_mode))
            os.utime(out, ns=(st.st_atime_ns, st.st_mtime_ns))
        return total

    def write_file(self, path: str, data: bytes, mode: int):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".v4tmp.")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
            os.chmod(tmp, mode)
            os.replace(tmp, path)
        except BaseException:
            if os.path.lexists(tmp):
                os.unlink(tmp)
            raise

    def install_file(self, src: str, dst: str, mode: int = 0o755):
        with open(src, "rb") as fh:
            self.write_file(dst, fh.read(), mode)

    def symlink(self, target: str, link: str):
        os.makedirs(os.path.dirname(link), exist_ok=True)
        if os.path.lexists(link):
            os.unlink(link)
        os.symlink(target, link)

    @staticmethod
    def not_nested(src: str, dst: str, label: str):
        if src == dst:
            return
        if (src + "/").startswith(dst + "/"):
            raise InstallError(f"{label} source is inside the destination: {src}")
        if (dst + "/").startswith(src + "/"):
            raise InstallError(f"{label} destination is inside the source: {dst}")

    def s_root(self):
        if self.dry:
            self.log(f"would copy {self.v4_source} -> {V4_DEST}")
            return "dry run"
        dst = self.D(V4_DEST)
        os.makedirs(dst, mode=0o755, exist_ok=True)
        if os.path.realpath(self.v4_source) == os.path.realpath(dst):
            return "already in place"
        self.not_nested(os.path.realpath(self.v4_source), os.path.realpath(dst), "Unix v4 root")
        n = self.copy_tree(self.v4_source, dst)
        self.info["root_files"] = str(n)
        return f"{n} files"

    def s_bin(self):
        if self.dry:
            self.log(f"would copy {self.bin_src} -> {PDP11_DEST}, install dispatcher and symlinks")
            return "dry run"
        dst = self.D(PDP11_DEST)
        os.makedirs(dst, mode=0o755, exist_ok=True)
        self.m.update(None, "copying binaries")
        if os.path.realpath(self.bin_src) != os.path.realpath(dst):
            self.not_nested(self.bin_src, os.path.realpath(dst), "v4linux bin")
            self.copy_tree(self.bin_src, dst, progress=False)
        if not os.access(os.path.join(dst, "v4linux"), os.X_OK):
            raise InstallError(f"installed emulator is not executable: {PDP11_DEST}/v4linux")
        self.install_file(os.path.join(self.bin_src, "v4linux-dispatch"), self.D(DISPATCH_DEST))
        self.install_file(self.uninstall_script, os.path.join(dst, "uninstall-script"))
        self.install_file(self.uninstall_boot, os.path.join(dst, "uninstall"))
        self.symlink(PDP11_DEST + "/uninstall", self.D("/usr/bin/v4-uninstall"))
        for tool in REQUIRED_TOOLS:
            self.symlink(f"{PDP11_DEST}/{tool}", self.D("/usr/bin/" + link_name(tool)))
        return f"{len(REQUIRED_TOOLS)} commands linked"

    def collect_man_pages(self):
        pages, seen = [], set()
        if os.path.isdir(self.man_src):
            for section in sorted(os.listdir(self.man_src)):
                sdir = os.path.join(self.man_src, section)
                if not section.startswith("man") or not os.path.isdir(sdir) and not os.path.islink(sdir):
                    continue
                if os.path.islink(sdir):
                    raise InstallError(f"refusing symlinked man source directory: {sdir}")
                for name in sorted(os.listdir(sdir)):
                    page = os.path.join(sdir, name)
                    if not os.path.isfile(page):
                        continue
                    rel = f"{section}/{name}" if name.endswith(".gz") else f"{section}/{name}.gz"
                    if not valid_man_rel(rel):
                        raise InstallError(f"invalid man page path: {rel}")
                    if rel in seen:
                        raise InstallError(f"multiple source man pages map to {rel}")
                    seen.add(rel)
                    pages.append((page, rel))
        if not pages:
            raise InstallError(f"no man pages found under {self.man_src}/man*/*")
        return pages

    def s_man(self):
        if self.dry:
            self.log(f"would install {len(self.man_pages)} man pages")
            return "dry run"
        dest_root, link_root, manifest = self.D(MAN_DEST), self.D(MAN_LINK_ROOT), self.D(MAN_MANIFEST)
        for d in (dest_root, link_root):
            if os.path.islink(d):
                raise InstallError(f"refusing symlinked man directory: {d}")
        os.makedirs(dest_root, mode=0o755, exist_ok=True)
        os.makedirs(link_root, mode=0o755, exist_ok=True)
        for d in (dest_root, link_root):
            if os.path.realpath(d) != d:
                raise InstallError(f"refusing non-canonical man directory: {d}")
        if os.path.islink(manifest):
            raise InstallError(f"refusing symlinked installation manifest: {manifest}")
        if os.path.lexists(manifest) and not os.path.isfile(manifest):
            raise InstallError(f"man installation manifest is not a regular file: {manifest}")

        if os.path.isfile(manifest):
            with open(manifest, "rb") as fh:
                old = [r.decode() for r in fh.read().split(b"\0") if r]
            for rel in old:
                if not valid_man_rel(rel):
                    raise InstallError(f"invalid path in {manifest}")
                section_dir = os.path.join(link_root, rel.split("/", 1)[0])
                if os.path.islink(section_dir):
                    raise InstallError(f"refusing symlinked man section directory: {section_dir}")
                link = os.path.join(link_root, rel)
                if os.path.islink(link) and os.readlink(link) == f"{MAN_DEST}/{rel}":
                    os.unlink(link)

        with open(manifest, "wb") as mf:
            os.chmod(manifest, 0o644)
            for i, (page, rel) in enumerate(self.man_pages, 1):
                self.tick()
                section = rel.split("/", 1)[0]
                dest_dir, link_dir = os.path.join(dest_root, section), os.path.join(link_root, section)
                for d in (dest_dir, link_dir):
                    if os.path.islink(d):
                        raise InstallError(f"refusing symlinked man section directory: {d}")
                os.makedirs(dest_dir, mode=0o755, exist_ok=True)
                os.makedirs(link_dir, mode=0o755, exist_ok=True)
                if os.path.realpath(link_dir) != link_dir:
                    raise InstallError(f"refusing non-canonical man section directory: {link_dir}")
                dest_file = os.path.join(dest_root, rel)
                with open(page, "rb") as fh:
                    data = fh.read()
                if not page.endswith(".gz"):
                    data = gzip.compress(data, mtime=0)
                self.write_file(dest_file, data, 0o644)
                link = os.path.join(link_root, rel)
                target = f"{MAN_DEST}/{rel}"
                if os.path.islink(link):
                    if os.readlink(link) != target:
                        raise InstallError(f"man page link exists with a different target: {link}")
                elif os.path.lexists(link):
                    raise InstallError(f"refusing to replace existing non-symlink man page: {link}")
                else:
                    os.symlink(target, link)
                mf.write(rel.encode() + b"\0")
                self.m.update(i / len(self.man_pages), f"{i}/{len(self.man_pages)} pages")
        self.info["man_count"] = str(len(self.man_pages))
        return f"{len(self.man_pages)} pages"

    def s_magic(self):
        if self.dry:
            self.log(f"would add managed block to {MAGIC_DEST}")
            return "dry run"
        dst = self.D(MAGIC_DEST)
        if os.path.islink(dst):
            raise InstallError(f"refusing symlinked magic database: {dst}")
        if os.path.lexists(dst) and not os.path.isfile(dst):
            raise InstallError(f"magic database is not a regular file: {dst}")
        uid, gid, mode = 0, 0, 0o644
        kept: list[str] = []
        if os.path.exists(dst):
            st = os.stat(dst)
            uid, gid, mode = st.st_uid, st.st_gid, stat.S_IMODE(st.st_mode)
            inside = found_begin = found_end = bad = False
            with open(dst, newline="") as fh:
                for line in fh:
                    bare = line.rstrip("\r\n")
                    if bare == MAGIC_BEGIN:
                        bad |= inside or found_begin
                        inside = found_begin = True
                    elif bare == MAGIC_END:
                        bad |= (not inside) or found_end
                        inside, found_end = False, True
                    elif not inside:
                        kept.append(line)
            if inside or found_begin != found_end or bad:
                raise InstallError(f"malformed v4linux magic block in {dst}; refusing to modify it")
        while kept and not kept[-1].strip():
            kept.pop()
        base = "".join(kept)
        if base and not base.endswith("\n"):
            base += "\n"
        with open(self.magic_src, "r", newline="") as fh:
            block = fh.read()
        text = (base + "\n" if base else "") + MAGIC_BEGIN + "\n" + block + "\n" + MAGIC_END + "\n"
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(dst), prefix=".magic.v4linux.")
        try:
            with os.fdopen(fd, "w", newline="") as fh:
                fh.write(text)
            if self.is_root:
                os.chown(tmp, uid, gid)
            os.chmod(tmp, mode)
            os.replace(tmp, dst)
        except BaseException:
            if os.path.lexists(tmp):
                os.unlink(tmp)
            raise
        return "updated"

    def s_service(self):
        if self.dry:
            self.log("would write runtime script and systemd unit")
            return "dry run"
        self.write_file(self.D(RUNTIME_SCRIPT), fill(RUNTIME_TEMPLATE).encode(), 0o755)
        self.write_file(self.D(SERVICE_FILE), fill(SERVICE_TEMPLATE).encode(), 0o644)
        return "runtime script + unit"

    def deactivate(self):
        if self.destdir or self.dry:
            return
        if os.path.exists(SERVICE_FILE) and shutil.which("systemctl"):
            self.sh("systemctl", "disable", "--now", SERVICE_NAME, check=False)
        for mp, recursive in ((HOST_MOUNT, True), (HOME_MOUNT, True), (TMP_MOUNT, True),
                              (GUEST_ROOT, False), (HOST_STAGING, True)):
            if is_mountpoint(mp):
                self.sh("umount", *(("-R",) if recursive else ()), mp, check=False)
        for name in BINFMT_NAMES:
            entry = os.path.join(BINFMT_DIR, name)
            if os.path.exists(entry):
                try:
                    with open(entry, "w") as fh:
                        fh.write("-1\n")
                except OSError:
                    pass
        if os.path.isdir(HOST_STAGING):
            try:
                os.rmdir(HOST_STAGING)
            except OSError:
                pass

    def s_activate(self):
        self.undo.append(("unmount guest environment", self.deactivate))
        if self.systemd:
            self.m.update(None, "systemd")
            self.sh("systemctl", "daemon-reload")
            rc, _ = self.sh("systemctl", "enable", "--now", SERVICE_NAME, check=False)
            if rc != 0:
                _, journal = self.sh("journalctl", "-u", SERVICE_NAME, "-n", "15", "--no-pager", check=False)
                tail = journal.splitlines()[-1] if journal else "see 'journalctl -u v4linux'"
                raise InstallError(f"{SERVICE_NAME} failed to start: {tail}")
            return "service enabled and started"
        self.sh(self.D(RUNTIME_SCRIPT))
        return "mounted (no systemd)"

    def s_verify(self):
        problems = []
        for tool in REQUIRED_TOOLS:
            link = "/usr/bin/" + link_name(tool)
            if not os.access(link, os.X_OK):
                problems.append(f"{link} is not executable")
        for mp in (GUEST_ROOT, HOST_MOUNT, HOME_MOUNT, TMP_MOUNT):
            if not is_mountpoint(mp):
                problems.append(f"{mp} is not mounted")
        for name in BINFMT_NAMES:
            entry = os.path.join(BINFMT_DIR, name)
            try:
                with open(entry) as fh:
                    if not fh.read().startswith("enabled"):
                        problems.append(f"binfmt handler {name} is disabled")
            except OSError:
                problems.append(f"binfmt handler {name} is not registered")
        if not problems:
            self.m.update(None, "running a guest program")
            probe = os.path.join(GUEST_ROOT, "bin", "echo")
            try:
                rc, out = self.sh(probe, "v4-ok", check=False, timeout=15)
                if "v4-ok" not in out:
                    problems.append(f"smoke test failed: {probe} v4-ok exited {rc}")
            except InstallError as exc:
                problems.append(f"smoke test could not run: {exc}")
        if problems:
            for p in problems:
                self.m.warn(p)
            return tui.WARN, f"{len(problems)} problem(s)"
        return "all checks passed"

    def build_summary(self):
        m = self.m
        prefix = f"{self.destdir}" if self.destdir else ""
        if self.dry:
            m.summary = [("Mode", "dry run - nothing was changed")]
            return
        m.summary = [
            ("Emulator", f"{PDP11_DEST}/v4linux"),
            ("Unix v4 root", f"{V4_DEST}  ({self.plan.variant or 'custom'})"),
            ("Toolchain", "v4-cc  v4-as  v4-ld  v4-ar  v4-strip  v4-disasm  v4-dumpinfo"),
            ("Man pages", f"{self.info.get('man_count', '?')} pages"),
        ]
        if self.activating:
            persist = f"{SERVICE_NAME} enabled" if self.systemd else "none (no systemd)"
            m.summary += [
                ("Guest root", f"{GUEST_ROOT}   (/host = host /, /home = host /home, /tmp = tmpfs)"),
                ("Persistence", persist),
            ]
        else:
            m.summary.append(("Staged in", prefix or "(dry run)"))
        if self.log_ok():
            m.summary.append(("Log", LOG_FILE))
        m.footer = ["Try it:    /opt/v4/sys/bin/sh or v4-cc example/hello.c",
                    "Remove it: sudo v4-uninstall [--purge-all]"]

    def log_ok(self) -> bool:
        return self.m.logfile is not None

def parse_args(argv):
    ap = argparse.ArgumentParser(
        prog="v4linux-setup.py",
        description="Install the v4linux emulator, PDP-11 toolchain and a Unix v4 root.",
        epilog="With no ROOT and no --variant, an interactive menu offers to download Unix v4.")
    ap.add_argument("bin_dir", metavar="BIN_DIR", help="bin directory produced by 'make' (contains v4linux)")
    ap.add_argument("root", metavar="ROOT", nargs="?",
                    help="extracted Unix v4 root directory, or a URL to a .tar.xz of one")
    ap.add_argument("--variant", choices=("stock", "symbols"),
                    help="download this Unix v4 image without asking")
    ap.add_argument("--cache-dir", default=".v4", metavar="DIR",
                    help="where downloaded images are kept (default: ./.v4)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--redownload", action="store_true", help="download again even if a copy exists")
    g.add_argument("--no-redownload", action="store_true", help="reuse an existing download")
    ap.add_argument("-y", "--yes", action="store_true",
                    help="never prompt: stock image, reuse existing download, replace active install")
    ap.add_argument("--plain", action="store_true", help="plain text output instead of the curses UI")
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="plain output with every command and its output")
    ap.add_argument("--dry-run", action="store_true", help="check inputs and show the steps; change nothing")
    ap.add_argument("--destdir", metavar="DIR",
                    help="stage files under DIR for packaging (no mounts, service or binfmt changes)")
    return ap.parse_args(argv)

def open_log(model: tui.Model, dry: bool, staged: bool):
    if dry or staged:
        return
    try:
        os.makedirs(os.path.dirname(LOG_FILE), exist_ok=True)
        model.logfile = open(LOG_FILE, "a", buffering=1)
        model.logfile.write(f"\n==== v4linux-setup {time.strftime('%Y-%m-%d %H:%M:%S')} ====\n")
    except OSError:
        model.logfile = None

def main(argv=None) -> int:
    args = parse_args(argv)
    destdir = os.path.realpath(args.destdir) if args.destdir else ""
    tty = sys.stdin.isatty() and sys.stdout.isatty()
    interactive = tty and not args.yes
    ui = tui.pick_ui(plain=args.plain or args.verbose, verbose=args.verbose)

    try:
        with ui:
            plan = make_plan(args, ui, interactive, destdir)
            if plan is None:
                print("Nothing installed.")
                return 0
            subtitle = f"{os.path.dirname(os.path.abspath(args.bin_dir))}  →  /opt/v4" if getattr(ui, "uni", False) \
                else f"{os.path.dirname(os.path.abspath(args.bin_dir))}  ->  /opt/v4"
            if destdir:
                subtitle += f"  (staged in {destdir})"
            model = tui.Model("v4linux - installer", subtitle, build_steps(plan, destdir))
            open_log(model, args.dry_run, bool(destdir))
            installer = Installer(args, plan, model)
            ui.run(model, installer.execute)
    except InstallError as exc:
        print(f"v4linux-setup: {exc}", file=sys.stderr)
        return 1

    for line in tui.format_result(model, getattr(ui, "uni", False)):
        print(line)
    if model.result in ("failed", "cancelled") and model.logfile is not None:
        print(f"\n  Full log: {LOG_FILE}")
    return {"ok": 0, "cancelled": 130}.get(model.result, 1)

if __name__ == "__main__":
    sys.exit(main())