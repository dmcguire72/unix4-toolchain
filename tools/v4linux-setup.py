def _unescape_mountinfo(field: str) -> str:
    out, i = [], 0
    while i < len(field):
        if field[i] == "\\" and i + 3 < len(field) and field[i + 1:i + 4].isdigit():
            out.append(chr(int(field[i + 1:i + 4], 8)))
            i += 4
        else:
            out.append(field[i])
            i += 1
    return "".join(out)

def is_mountpoint(path: str) -> bool:
    path = os.path.realpath(path)
    try:
        with open("/proc/self/mountinfo") as fh:
            for line in fh:
                parts = line.split()
                if len(parts) > 4 and _unescape_mountinfo(parts[4]) == path:
                    return True
    except OSError:
        pass
    return False

def valid_man_rel(rel: str) -> bool:
    if "/" not in rel:
        return False
    section, name = rel.split("/", 1)
    return section.startswith("man") and bool(name) and "/" not in name and name not in (".", "..")

def resolve_root_dir(path: str) -> str:
    if not os.path.isdir(os.path.join(path, "bin")):
        for sub in sorted(os.listdir(path)):
            cand = os.path.join(path, sub)
            if os.path.isdir(os.path.join(cand, "bin")):
                return cand
    return path

def is_url(text: str) -> bool:
    return text.startswith(("http://", "https://", "ftp://", "file://"))

